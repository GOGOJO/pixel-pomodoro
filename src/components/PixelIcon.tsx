export type IconName = keyof typeof ICONS;

const COLORS: Record<string, string> = {
  "#": "currentColor",
  r: "#e8604c",
  g: "#5fa84a",
  w: "#ffd0b8",
};

export const PixelIcon = memo(function PixelIcon({
  name,
  size = 18,
  className,
  title,
}: {
  name: IconName;
  size?: number | string;
  className?: string;
  title?: string;
}) {
  const rows = ICONS[name];
  const rects: React.ReactNode[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const c = row[x];
      if (c === ".") continue;
      rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={1.02} height={1.02} fill={COLORS[c]} />);
    }
  });
  return (
    <svg
      viewBox="0 0 9 9"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      className={className}
      aria-hidden={title ? undefined : true}
      role={title ? "img" : undefined}
    >
      {title && <title>{title}</title>}
      {rects}
    </svg>
  );
});
